// Package tools — реестр инструментов MCP-сервера ФГИС «Аршин»
// и заслоны вокруг них.
//
// Сервер только читает публичный реестр, поэтому главный риск здесь
// не порча данных, а две другие поломки:
//
//  1. Блокировка адреса. ФГИС пускает не больше 2 запросов в секунду
//     с одного IP и за упорство банит адрес на часы. Модель охотно
//     зовёт инструменты параллельно и «перебирает варианты», поэтому
//     частоту держит клиент (arshin), а число запросов на один вызов
//     инструмента ограничено здесь (MaxRequestsPerCall).
//
//  2. Ответ, который не доезжает. Клиент MCP режет результат по числу
//     токенов, и сотня карточек поверок до модели не доходит вовсе.
//     Обрезка здесь — разница между «данные неполны» и молчаливым
//     циклом из повторных вызовов.
//
// Заслон записи (режим только чтения по умолчанию) оставлен по
// стандарту: пишущих инструментов пока нет, но первый не должен
// появиться без него.
package tools

import (
	"fmt"
	"unicode/utf8"
)

// Mode — режим работы подключения.
type Mode string

const (
	// ModeReadOnly — только чтение. Значение по умолчанию.
	ModeReadOnly Mode = "read-only"
	// ModeWrite — чтение и запись.
	ModeWrite Mode = "write"
)

// Safety — права и пороги текущего подключения.
type Safety struct {
	Mode Mode

	// MaxResponseBytes — потолок размера ответа инструмента.
	//
	// Клиент режет результат инструмента по числу токенов (обычно
	// 25 000), и ответ сверх этого не доезжает вовсе. Плотный JSON
	// с кириллицей — около двух байт на токен, поэтому потолок
	// держится заметно ниже.
	MaxResponseBytes int

	// MaxRequestsPerCall — сколько запросов к ФГИС может сделать один
	// вызов инструмента (перебор лет в check_instrument и т. п.).
	// При паузе 0,6 с восемь запросов — около пяти секунд; дальше
	// растёт уже риск таймаута клиента и блокировки адреса.
	MaxRequestsPerCall int
}

// DefaultSafety — осторожные значения по умолчанию.
func DefaultSafety() Safety {
	return Safety{
		Mode:               ModeReadOnly,
		MaxResponseBytes:   40_000,
		MaxRequestsPerCall: 8,
	}
}

// ErrWriteDisabled возвращается, когда write-инструмент вызван
// в режиме только для чтения.
type ErrWriteDisabled struct {
	Tool string
}

func (e ErrWriteDisabled) Error() string {
	// Сообщение покрывает оба транспорта: локально режим задан
	// переменной окружения, по сети — тем, какой токен прописан
	// в этом клиенте. Не назвать оба варианта — значит отправить
	// человека править не то место.
	return fmt.Sprintf(
		"Инструмент %s изменяет данные, а у этого подключения прав на запись нет.\n\n"+
			"Это защита по умолчанию: доступ на запись открывает человек в конфигурации,\n"+
			"а не удачная формулировка в разговоре.\n\n"+
			"Если сервер запущен локально (stdio) — добавьте в его конфигурацию:\n"+
			"    RST_ALLOW_WRITES=true\n"+
			"и перезапустите клиент.\n\n"+
			"Если сервер сетевой — в этом клиенте прописан токен только на чтение\n"+
			"(scope rst:read). Запись возможна там, где прописан пишущий токен\n"+
			"или где при OAuth-подключении отмечена галочка «Изменение».\n\n"+
			"Текущее состояние подключения показывает rst_status.",
		e.Tool)
}

// CheckWrite пропускает запись только в режиме ModeWrite.
func (s Safety) CheckWrite(tool string) error {
	if s.Mode != ModeWrite {
		return ErrWriteDisabled{Tool: tool}
	}
	return nil
}

// TrimResponse укорачивает слишком длинный ответ, объясняя, что
// произошло.
//
// JSON укорачивается по элементам — так, чтобы наружу вышел валидный
// документ с отметкой об обрезке (см. trim.go). Байтовый срез остаётся
// только для ответов, которые не JSON.
func (s Safety) TrimResponse(body string) string {
	if s.MaxResponseBytes <= 0 || len(body) <= s.MaxResponseBytes {
		return body
	}

	// Хвост с объяснением сам занимает место, и без запаса под него
	// обрезанный ответ снова оказывается длиннее потолка.
	const noteBudget = 400
	limit := s.MaxResponseBytes - noteBudget
	if limit < 0 {
		limit = 0
	}

	if trimmed, ok := trimJSON(body, limit); ok {
		return trimmed
	}

	if limit > len(body) {
		limit = len(body)
	}
	// Срез по байтам легко приходится на середину кириллической буквы,
	// а битый UTF-8 ломает уже не смысл ответа, а сам протокол.
	for limit > 0 && !utf8.ValidString(body[:limit]) {
		limit--
	}
	return body[:limit] + fmt.Sprintf(
		"\n\n[…ответ обрезан на %d байтах из %d — это фрагмент, а не документ, "+
			"и разбирать его как целое нельзя. Повторный вызов с теми же аргументами "+
			"вернёт ровно то же самое: сузьте выборку.]",
		limit, len(body))
}
