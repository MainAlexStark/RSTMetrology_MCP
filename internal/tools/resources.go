package tools

import (
	"context"

	"github.com/MainAlexStark/rst-metrology-mcp/internal/mcp"
)

// Ресурсы MCP — второй, не инструментальный способ отдать данные:
// инструмент модель вызывает сама, ресурс клиент читает по адресу
// и обычно показывает в начале разговора.
//
// Здесь это памятка по полям реестра. Без неё модель путает vri_id
// с номером свидетельства, mit_number с заводским номером и ищет за
// текущий год — и каждую из этих ошибок оплачивает лишним запросом
// к ФГИС с её лимитом в 2 запроса в секунду.

// GuideURI — адрес памятки.
const GuideURI = "rst://guide/fields"

const guide = `# ФГИС «Аршин»: что есть что

## Поверка (search_verifications, get_verification)
- vri_id — идентификатор записи о поверке («1-340080782»). По нему — карточка.
- result_docnum — номер свидетельства («С-…») или извещения о непригодности («И-…»). Не идентификатор.
- mit_number — регистрационный номер ТИПА СИ в реестре («16078-05»). Один на все экземпляры типа.
- mi_number — заводской номер ЭКЗЕМПЛЯРА. У приборов разных типов номера совпадают.
- mit_title / mit_notation / mi_modification — наименование, обозначение типа, модификация.
- verification_date / valid_date — дата поверки и «действительна до» (YYYY-MM-DD).
- applicability — true: пригодно (свидетельство), false: непригодно (извещение).
- Запись может быть модифицирована (есть новая версия) или аннулирована — это видно только в карточке.

## Поиск
- search ищет по всем полям; пишите любые известные слова в любом порядке, части слов тоже
  годятся: «бетар сгв», «единица манометр», «кировский цсм весы». Найдутся записи, где есть все слова.
- Поля (mit_title, org_title, title, manufacturers…) ищут так же, но только в своём поле.
- mit_number и mi_number сравниваются точно; для части заводского номера — «*4860*» или search.
- В ответе sent_to_fgis — что ушло в ФГИС, candidates — сколько она нашла; если кандидатов
  больше, чем просмотрено за вызов, будет next_start — продолжайте с него.
- Без year или date_from ФГИС ищет только в текущем году.
- Слишком широкий запрос (нет фильтров, большой период) ФГИС отклоняет — сужайте годом и номером типа.
- Не больше 100 записей за запрос; дальше — start.
- Лимит ФГИС — 2 запроса в секунду с адреса, сервер держит паузу сам. Не перебирайте варианты вслепую.

## Тип СИ (search_types, get_type)
- Карточка типа: изготовитель, срок действия свидетельства об утверждении типа,
  межповерочный интервал, методика поверки, описание типа.
- get_type принимает mit_uuid, ссылку mit_url из карточки поверки или регистрационный номер.

## Частые вопросы
- «Поверен ли прибор N?» → check_instrument(mi_number, mit_number).
- «Какие приборы поверяла организация X в мае?» → search_verifications(org_title, date_from, date_to).
- «Какой МПИ у типа?» → get_type(номер типа); МПИ — в card.mpi, в месяцах.
- «Знаю только изготовителя и что это счётчик» → search_types(search: "бетар счетчик").
`

// RegisterResources добавляет ресурсы сервера.
func (r *Registry) RegisterResources() {
	r.server.RegisterResource(mcp.Resource{
		Name:        "fields_guide",
		Description: "Памятка: поля реестра ФГИС «Аршин» (vri_id, mit_number, mi_number…) и особенности поиска",
		URI:         GuideURI,
		MIMEType:    "text/markdown",
		Handler: func(context.Context) (string, error) {
			return guide, nil
		},
	})
}
