// Package arshin — клиент публичного API ФГИС «Аршин» Росстандарта
// (раздел «РСТ-метрология», https://fgis.gost.ru/fundmetrology/eapi).
//
// Пакет не знает ни про MCP, ни про инструменты: это самостоятельная
// библиотека, которую можно взять отдельно.
//
// Что известно о внешней системе и на чём построен клиент
// (руководство «Внешние публичные интерфейсы» v2.2 и наблюдения
// работающих интеграций):
//
//   - GET /vri — поиск сведений о результатах поверки (список),
//     GET /vri/{vri_id} — карточка одной поверки;
//   - GET /mit — поиск утверждённых типов средств измерений,
//     GET /mit/{mit_uuid} — карточка типа;
//   - ключ не нужен, но с одного IP разрешено не больше 2 запросов
//     в секунду: сверх этого — 429, при упорстве — блокировка адреса;
//   - сервис отвечает только российским адресам; из-за границы
//     соединение просто висит до таймаута;
//   - без year или verification_date_start поиск поверок идёт только
//     по текущему году — частая причина «прибор не найден»;
//   - слишком широкий запрос получает 400 или 408 («превышен лимит
//     на поиск»), rows не больше 100;
//   - даты приходят и как dd.mm.yyyy, и как ISO;
//   - вместо JSON иногда приходит HTML-заглушка со статусом 200.
//
// Поэтому клиент держит паузу между любыми запросами процесса,
// повторяет вызов на 429/5xx/сетевой сбой, распознаёт заглушку
// и раскладывает отказы по классам (Hint).
